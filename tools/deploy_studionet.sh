#!/usr/bin/env bash
# Deploy the EquivalenceKit reference contracts to StudioNet and record the evidence.
#
# StudioNet is gasless: 0 GEN is expected. Run with the network already set:
#     genlayer network set studionet
#
# Usage:
#     bash tools/deploy_studionet.sh
#
# Writes deployments/studionet.md with address, deploy tx, explorer link, and schema.
# Never prints or stores a private key.

set -euo pipefail

cd "$(dirname "$0")/.."

NETWORK="${NETWORK:-studionet}"
RPC="${RPC:-https://studio.genlayer.com/api}"
# The StudioNet explorer is explorer-studio.genlayer.com and uses /address/<addr> and
# /tx/<hash> paths. (The older genlayer-explorer.vercel.app host is currently paused.)
EXPLORER="https://explorer-studio.genlayer.com"
OUT="deployments/studionet.md"

mkdir -p deployments

explorer_tx() { echo "${EXPLORER}/tx/${1}"; }
explorer_addr() { echo "${EXPLORER}/address/${1}"; }

stamp() {
  echo
  echo "## $(date -u '+%Y-%m-%d %H:%M:%S UTC')"
  echo
  echo "- network: \`${NETWORK}\`"
  echo "- rpc: \`${RPC}\`"
  echo "- account: \`$(genlayer account list 2>/dev/null | awk '/\* /{print $1; exit}')\`"
  echo
}

deploy_one() {
  local label="$1"
  local file="$2"

  echo "=== deploying ${label} (${file}) ==="
  local receipt
  receipt="$(genlayer deploy --contract "${file}" --rpc "${RPC}" 2>&1)"

  # The CLI ends with a labelled summary:
  #     Transaction Hash: 0x<64 hex>
  #     Contract Address: 0x<40 hex>
  # Parse by label, not by order, so a stray hash in a receipt cannot be misattributed.
  local address
  address="$(grep -oE 'Contract Address:[[:space:]]*0x[0-9a-fA-F]{40}' <<<"${receipt}" \
            | grep -oE '0x[0-9a-fA-F]{40}' | head -1)"
  local tx
  tx="$(grep -oE 'Transaction Hash:[[:space:]]*0x[0-9a-fA-F]{64}' <<<"${receipt}" \
        | grep -oE '0x[0-9a-fA-F]{64}' | head -1)"

  # Fall back to a bare hash only if the labels were not printed.
  if [[ -z "${address}" ]]; then
    address="$(grep -oE '0x[0-9a-fA-F]{40}' <<<"${receipt}" | head -1)"
  fi

  echo "--- raw receipt ---"
  echo "${receipt}"

  if [[ -z "${address}" ]]; then
    echo "!! could not parse an address out of the deploy output for ${label}" >&2
    return 1
  fi

  {
    echo "### ${label}"
    echo
    echo "| Field | Value |"
    echo "|---|---|"
    echo "| Contract file | \`${file}\` |"
    echo "| Address | \`${address}\` |"
    echo "| Deploy tx | \`${tx:-see receipt below}\` |"
    echo "| Explorer (address) | $(explorer_addr "${address}") |"
    if [[ -n "${tx:-}" ]]; then
      echo "| Explorer (tx) | $(explorer_tx "${tx}") |"
    fi
    echo
    echo "<details><summary>Deploy output</summary>"
    echo
    echo '```'
    echo "${receipt}"
    echo '```'
    echo
    echo "</details>"
    echo
    echo "#### Schema"
    echo
    echo '```json'
    genlayer schema "${address}" --rpc "${RPC}" 2>&1 || echo '{"error":"schema fetch failed"}'
    echo '```'
    echo
  } >>"${OUT}"

  echo "${label} -> ${address}"
}

main() {
  if [[ ! -f "${OUT}" ]]; then
    {
      echo "# EquivalenceKit — StudioNet deployments"
      echo
      echo "StudioNet is gasless; every deploy below is expected to cost **0 GEN**."
      echo
      echo "Generated by \`tools/deploy_studionet.sh\`. Regenerate rather than hand-edit."
      echo
    } >"${OUT}"
  fi

  stamp >>"${OUT}"

  deploy_one "VerdictJudge" "verdict_judge.py"
  deploy_one "WebFactAttestor" "web_fact_attestor.py"

  echo
  echo "wrote ${OUT}"
}

main "$@"
