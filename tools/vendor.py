#!/usr/bin/env python3
"""Vendor the pure primitives into single-file contracts.

Deployment has no documented sibling-module imports, so each contract carries an inlined
copy of the primitives it needs. This tool renders that block deterministically, updates
every contract between the markers, and can check that committed blocks are fresh.

Usage:
    python3 tools/vendor.py          # rewrite generated blocks
    python3 tools/vendor.py --check  # exit 1 if any block is stale
"""

from __future__ import annotations

import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "equivalencekit"
CONTRACTS = ROOT / "contracts"

MODULES = (
    "errors.py",
    "bounds.py",
    "normalize.py",
    "digest.py",
    "compare.py",
    "parsing.py",
    "patterns.py",
)
EXCLUDE_NAMES = {"normalize_url"}
EXCLUDE_IMPORT_MODULES = {"urllib.parse", "__future__"}

BEGIN = "# BEGIN VENDORED PRIMITIVES"
END = "# END VENDORED PRIMITIVES"


def _module_nodes(path: Path):
    tree = ast.parse(path.read_text(), filename=str(path))
    nodes = []
    for node in tree.body:
        if isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
            continue  # module docstring
        if isinstance(node, ast.ImportFrom) and ((node.level or 0) > 0 or (node.module or "").startswith(".")):
            continue  # package-relative import
        if isinstance(node, ast.FunctionDef) and node.name in EXCLUDE_NAMES:
            continue
        if isinstance(node, (ast.AnnAssign, ast.Assign)):
            targets = [node.target] if isinstance(node, ast.AnnAssign) else node.targets
            names = [target.id for target in targets if isinstance(target, ast.Name)]
            if names and all(name in EXCLUDE_NAMES for name in names):
                continue
        nodes.append(node)
    return nodes


def render_block() -> str:
    imports = {}
    body = []
    for filename in MODULES:
        for node in _module_nodes(PACKAGE / filename):
            if isinstance(node, ast.Import):
                for alias in node.names:
                    if alias.name in EXCLUDE_IMPORT_MODULES:
                        continue
                    imports.setdefault(("import", alias.name, alias.asname), None)
                continue
            if isinstance(node, ast.ImportFrom):
                if node.module in EXCLUDE_IMPORT_MODULES:
                    continue
                for alias in node.names:
                    imports.setdefault(("from", node.module, alias.name, alias.asname), None)
                continue
            body.append(ast.unparse(node))

    lines = [
        BEGIN,
        "# Generated by tools/vendor.py from equivalencekit/*.py.",
        "# DO NOT EDIT THIS BLOCK. Edit the package and run: python3 tools/vendor.py",
    ]
    plain = sorted(key[1] for key in imports if key[0] == "import")
    for module in plain:
        lines.append(f"import {module}")
    grouped = {}
    for key in imports:
        if key[0] != "from":
            continue
        _, module, name, asname = key
        grouped.setdefault(module, []).append((name, asname))
    for module in sorted(grouped):
        items = grouped[module]
        rendered = ", ".join(name if asname is None else f"{name} as {asname}" for name, asname in items)
        lines.append(f"from {module} import {rendered}")
    lines.append("")
    lines.extend(body)
    lines.append(END)
    return "\n".join(lines)


def _replace_block(text: str, block: str) -> str:
    begin = text.index(BEGIN)
    end = text.index(END, begin) + len(END)
    return text[:begin] + block + text[end:]


def main() -> int:
    check = "--check" in sys.argv
    block = render_block()
    stale = []
    for path in sorted(CONTRACTS.rglob("*.py")):
        text = path.read_text()
        if BEGIN not in text or END not in text:
            continue
        current = text[text.index(BEGIN) : text.index(END) + len(END)]
        if current != block:
            stale.append(path)
            if not check:
                path.write_text(_replace_block(text, block))
    if check and stale:
        for path in stale:
            print(f"stale vendored block: {path.relative_to(ROOT)}")
        return 1
    if not check:
        for path in stale:
            print(f"updated {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
